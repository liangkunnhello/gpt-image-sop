/** 同批中位长度：真实那批是 422 字 */
const MEDIAN = 422

describe('checkPromptIntegrity（真实事故回归）', () => {
  it('4 条被截断的提示词全部能被认出', () => {
    for (const prompt of TRUNCATED) {
      expect(checkPromptIntegrity(prompt, MEDIAN), prompt.slice(0, 20)).not.toBeNull()
    }
  })

  it('正常提示词不被误伤（第二版规则曾在这两条上误报）', () => {
    for (const prompt of NORMAL) {
      expect(checkPromptIntegrity(prompt, MEDIAN), prompt.slice(0, 20)).toBeNull()
    }
  })

  it('未闭合的「是最强信号，优先报出来', () => {
    const reason = checkPromptIntegrity(TRUNCATED[0], MEDIAN)
    expect(reason).toContain('引号没闭合')
  })

  it('只有 48 字的那条按「过短」报，而不是按结尾报', () => {
    const reason = checkPromptIntegrity(TRUNCATED[2], MEDIAN)
    expect(reason).toContain('只有 48 字')
  })
})

describe('checkPromptsIntegrity（整批）', () => {
  it('混入 4 条截断时，下标与数量都准确', () => {
    // 按真实那批的顺序还原：正常 + 截断交错
    const batch = [...NORMAL, ...TRUNCATED, ...NORMAL]
    const issues = checkPromptsIntegrity(batch)
    const indexes = issues.map((item) => item.index)
    // 截断的 4 条落在下标 2..5
    expect(indexes.sort()).toEqual([2, 3, 4, 5])
  })

  it('全部正常时一条都不报', () => {
    expect(checkPromptsIntegrity(NORMAL)).toEqual([])
  })

  it('空批不报，也不该崩', () => {
    expect(checkPromptsIntegrity([])).toEqual([])
  })
})

describe('token 预算（截断的根因）', () => {
  it('单批要给出足够写完的输出预算', () => {
    // 实测一条 380~460 字中文 ≈ 600~900 token，每条至少留 900
    expect(tokensForPrompts(PROMPTS_PER_BATCH)).toBeGreaterThanOrEqual(PROMPTS_PER_BATCH * 900)
  })

  it('单批 12 条的预算要覆盖实测需求（12 条约 8100 token），留出余量', () => {
    /**
     * 截断的真正根因是「预算不足」，不是「批次太大」：
     * 原来每条只给 500，12 条才 6000，写到第 11 条就没了。
     * 现在每条 900（12 条 10800），实测 12 条约需 8100，余量约 33%。
     * 所以批大小可以留在 12 —— 批数少一次就少一次固定开销。
     */
    expect(PROMPTS_PER_BATCH).toBe(12)
    expect(tokensForPrompts(12)).toBeGreaterThanOrEqual(8100)
    // 但不能顶到渠道上限，否则会被 400 拒掉
    expect(tokensForPrompts(12)).toBeLessThanOrEqual(32000)
  })

  it('条数再多也封顶在渠道能接受的上限内', () => {
    expect(tokensForPrompts(500)).toBeLessThanOrEqual(32000)
  })
})
